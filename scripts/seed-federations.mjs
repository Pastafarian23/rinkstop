#!/usr/bin/env node
// scripts/seed-federations.mjs
//
// One-shot seed of public.federations from src/lib/federations.ts.
// Run after applying 2026-07-23_federation_registrations.sql.
// Idempotent (upserts on slug = country code lowercase).
//
// Usage:
//   node scripts/seed-federations.mjs
//
// Reads the FEDERATIONS constant from src/lib/federations.ts and
// inserts one row per IIHF member. category defaults to 'all'
// (USA Hockey coaching + officiating live in separate rows added
// by a follow-up migration).

import { createRequire } from 'module';
import { readFileSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';

// Import the FEDERATIONS constant via tsx-style require shim —
// Next handles .ts via its bundler; we use a tiny regex extractor.
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const tsPath = path.resolve(__dirname, '../src/lib/federations.ts');
const ts = readFileSync(tsPath, 'utf8');

// Naive extractor: find each { countryCode, countryName, federationName,
// federationUrl } block. Good enough for the constant shape we control.
const rows = [];
const blockRe = /\{\s*countryCode:\s*'([A-Z]{2})',\s*countryName:\s*'([^']+)',[\s\S]*?federationName:\s*'([^']+)',\s*federationUrl:\s*'([^']+)'/g;
let m;
while ((m = blockRe.exec(ts)) !== null) {
  rows.push({
    slug: m[1].toLowerCase(),
    name: m[3],
    country_code: m[1],
    website_url: m[4],
  });
}

console.log(`Parsed ${rows.length} federations from ${tsPath}`);
if (rows.length === 0) {
  console.error('No rows parsed — regex may need updating.');
  process.exit(1);
}

// Print SQL to stdout for manual review, then attempt to apply via
// supabaseAdmin. Falls back to print-only if env vars are missing.
const sqlHeader = `-- Generated by scripts/seed-federations.mjs on ${new Date().toISOString()}
-- Idempotent UPSERT into public.federations
-- Run after applying 2026-07-23_federation_registrations.sql

`;

const values = rows.map((r, i) => {
  const escName = r.name.replace(/'/g, "''");
  return `  ('${r.slug}', '${escName}', '${r.country_code}', 'all', '${r.website_url}')`;
}).join(',\n');

const sql = sqlHeader + `INSERT INTO public.federations (slug, name, country_code, category, website_url) VALUES\n${values}\nON CONFLICT (slug) DO UPDATE SET\n  name = EXCLUDED.name,\n  country_code = EXCLUDED.country_code,\n  website_url = EXCLUDED.website_url,\n  is_active = true;`;

console.log(sql);

// Optionally apply via Supabase Management API if credentials present.
const credPath = '.env';
try {
  const cred = JSON.parse(readFileSync(credPath, 'utf8'));
  const projectRef = cred.projectRef || 'yszheonqyyskkjoxoexk';
  const pat = cred.managementApiPat || cred.serviceRoleKey;
  if (!pat) {
    console.log('\n[skip apply] No managementApiPat or serviceRoleKey in credentials file. Pipe this SQL to psql or the Supabase SQL editor.');
    process.exit(0);
  }
  const res = await fetch(`https://api.supabase.com/v1/projects/${projectRef}/database/query`, {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${pat}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ query: sql }),
  });
  if (!res.ok) {
    console.error(`[apply failed] ${res.status}: ${await res.text()}`);
    process.exit(1);
  }
  console.log(`\n[applied] ${rows.length} federations upserted.`);
} catch (e) {
  console.log(`\n[skip apply] ${e.message}. Pipe this SQL manually.`);
}
